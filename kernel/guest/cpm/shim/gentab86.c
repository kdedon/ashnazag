/*
 * gentab86 -- the 8086 assembly decoder's base map, from the C decoder.
 *
 *	gentab86 > i86tab.s
 *
 * Per opcode: op, x and the form word, high byte first.  Form bit 0x8000
 * marks the bytes the C decoder keeps: the prefixes and the forms whose
 * tail needs the opcode (D_O).
 */
#include <stdio.h>
#include "i86dec.c"

int
main()
{
	int op, f;

	printf("| generated by gentab86 from the C decoder\n\t.data\n\t.globl\ti86tab\n\t.even\ni86tab:\n");
	for (op = 0; op < 256; op++) {
		f = bform[op];
		if (ispfx[op] || (f & D_O))
			f |= 0x8000;
		printf("\t.byte\t%d,%d,%d,%d\t| %02X\n", bop[op], bx[op], f >> 8 & 0xff, f & 0xff, op);
	}
	return 0;
}
