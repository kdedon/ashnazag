/*
 * gentab -- the assembly decoders' base maps, from the C decoders.
 *
 *	gentab z80 > z80tab.s
 *
 * One 8-byte record per opcode: len, op, fl, x, y, then how the operand
 * follows (Z80K_*), and two zero bytes.  Built on the host from the
 * reference decoder, so the two cannot disagree about the base map.
 */
#include <stdio.h>
#include <string.h>
#include "z80.h"

#define	Z80K_NONE	0
#define	Z80K_BYTE	1
#define	Z80K_REL	2
#define	Z80K_WORD	3
#define	Z80K_PFX	4

static void
z80tab()
{
	static char m[0x10000];
	struct z80in in;
	int op, k;

	printf("| generated by gentab from the C decoder\n\t.data\n\t.globl\tz80tab, z80par\n\t.even\nz80tab:\n");
	for (op = 0; op < 256; op++) {
		m[0] = op;
		z80dec(m, 0, &in);
		if (in.fl & ZF_PFX)
			k = Z80K_PFX;
		else if (in.len == 1)
			k = Z80K_NONE;
		else if (in.len == 3)
			k = Z80K_WORD;
		else if (in.op == Z_JR || in.op == Z_DJNZ)
			k = Z80K_REL;
		else
			k = Z80K_BYTE;
		printf("\t.byte\t%d,%d,%d,%d,%d,%d,0,0\t| %02X\n",
		    in.len, in.op, in.fl, in.x, in.y, k, op);
	}
	/* even parity of each byte, the 8080's P */
	printf("z80par:\n");
	for (op = 0; op < 256; op++) {
		printf("%s%d%s", op % 16 ? "," : "\t.byte\t", (0x6996 >> ((op ^ op >> 4) & 15) & 1) ^ 1,
		    op % 16 == 15 ? "\n" : "");
	}
}

int
main(argc, argv)
	int argc;
	char **argv;
{
	if (argc == 2 && strcmp(argv[1], "z80") == 0)
		z80tab();
	else
		return 2;
	return 0;
}
