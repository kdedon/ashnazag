int mig_input_translate(unsigned int set, unsigned int code)
{
    if (code >= 128) return -1;
    if (set == EVK_AMIGA) return code <= 0x67 ? (int)code : -1;
    if (set == EVK_ADB) return adb[code] == 255 ? -1 : adb[code];
    if (set == EVK_IKBD) return ikbd[code] == 255 ? -1 : ikbd[code];
    return -1;
}
void mig_input_init(struct mig_input *q)
{
    memset(q, 0, sizeof *q);
    q->magic = MIG_INPUT_MAGIC;
    q->version = MIG_INPUT_VERSION;
}
void mig_input_reset(struct mig_input *q, struct mig_input_state *s)
{
    memset(s, 0, sizeof *s);
    s->generation = q->generation;
    if (q->reset == q->ack) {
        MIG_INPUT_BARRIER();
        q->reset++;
    }
}
static int post(struct mig_input *q, struct mig_input_state *s,
    unsigned short type, unsigned short code, short x, short y)
{
    unsigned int head = q->head;
    struct mig_input_event *e;
    if (q->ready != 1 || q->reset != q->ack) return 0;
    if (head - q->tail >= MIG_INPUT_COUNT) {
        mig_input_reset(q, s);
        return 0;
    }
    e = &q->event[head % MIG_INPUT_COUNT];
    e->type = type; e->code = code;
    e->qualifier = s->qualifier | (type == 2 ? 0x8000 : 0);
    if (type == 1 && ((code & 127) == 0x0f ||
        ((code & 127) >= 0x1d && (code & 127) <= 0x1f) ||
        ((code & 127) >= 0x2d && (code & 127) <= 0x2f) ||
        ((code & 127) >= 0x3c && (code & 127) <= 0x3f) ||
        (code & 127) == 0x43 || (code & 127) == 0x4a ||
        ((code & 127) >= 0x5a && (code & 127) <= 0x5e)))
        e->qualifier |= 0x100;
    e->reserved = 0; e->x = x; e->y = y;
    MIG_INPUT_BARRIER();
    q->head = head + 1;
    return 1;
}
static int key(struct mig_input *q, struct mig_input_state *s, int k, int down)
{
    if (s->keys[k] == down) return 0;
    s->keys[k] = down;
    if (k >= 0x60 && k <= 0x67) {
        unsigned short bit = 1U << (k - 0x60);
        if (k == 0x62) {
            if (down) s->qualifier ^= bit;
        } else if (down) s->qualifier |= bit;
        else s->qualifier &= ~bit;
    }
    return post(q, s, 1, k | (down ? 0 : 0x80), 0, 0);
}
int mig_input_event(struct mig_input *q, struct mig_input_state *s,
    unsigned int set, unsigned int flags, unsigned int type,
    unsigned int code, long value)
{
    int k, i;
    unsigned short bit;
    if (s->generation != q->generation) {
        memset(s, 0, sizeof *s);
        s->generation = q->generation;
    }
    if (type == IE_DROP) { mig_input_reset(q, s); return 0; }
    if (q->ready != 1 || q->reset != q->ack) return 0;
    switch (type) {
    case IE_KEY:
        k = mig_input_translate(set, code);
        if (k < 0) return 0;
        if (k == 0x62 && (flags & EVF_CAPSLATCH)) {
            key(q, s, k, 1);
            return key(q, s, k, 0);
        }
        if (s->sources[code] == (value != 0)) return 0;
        s->sources[code] = value != 0;
        if (!value)
            for (i = 0; i < 128; i++)
                if (s->sources[i] && mig_input_translate(set, i) == k)
                    return 0;
        return key(q, s, k, value != 0);
    case IE_REL:
        if (code > IE_RELY) return 0;
        if (value > 32767) value = 32767;
        if (value < -32768) value = -32768;
        return post(q, s, 2, 0xff, code == IE_RELX ? value : 0,
            code == IE_RELY ? value : 0);
    case IE_BTN:
        if (code < 1 || code > 3) return 0;
        /* Control-click is the menu button on a one-button mouse */
        if (code == 1 && (value ? (s->qualifier & 8) != 0 : s->menubtn)) {
            s->menubtn = value != 0;
            code = 2;
        }
        bit = code == 1 ? 0x4000 : code == 2 ? 0x2000 : 0x1000;
        if (!!(s->qualifier & bit) == !!value) return 0;
        if (value) s->qualifier |= bit; else s->qualifier &= ~bit;
        return post(q, s, 2, (code == 1 ? 0x68 : code == 2 ? 0x69 : 0x6a) |
            (value ? 0 : 0x80), 0, 0);
    }
    return 0;
}
